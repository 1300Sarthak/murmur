// MARK: - Global hotkeys (Carbon: no Accessibility permission needed, delivers press and release)

final class HotKeys {
    static let shared = HotKeys()
    private var handlers: [UInt32: (Bool) -> Void] = [:]
    private var refs: [UInt32: EventHotKeyRef] = [:]
    private var installed = false

    func register(id: UInt32, keyCode: Int, modifiers: Int = 0, handler: @escaping (_ pressed: Bool) -> Void) {
        installIfNeeded()
        unregister(id: id)
        var ref: EventHotKeyRef?
        let hkID = EventHotKeyID(signature: OSType(0x4D524D52) /* MRMR */, id: id)
        if RegisterEventHotKey(UInt32(keyCode), UInt32(modifiers), hkID, GetApplicationEventTarget(), 0, &ref) == noErr, let ref {
            refs[id] = ref
            handlers[id] = handler
        } else {
            NSLog("Murmur: could not register hotkey \(id)")
        }
    }

    func unregister(id: UInt32) {
        if let ref = refs.removeValue(forKey: id) { UnregisterEventHotKey(ref) }
        handlers[id] = nil
    }

    private func installIfNeeded() {
        guard !installed else { return }
        installed = true
        var specs = [
            EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed)),
            EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyReleased)),
        ]
        InstallEventHandler(GetApplicationEventTarget(), { _, event, _ in
            guard let event else { return OSStatus(eventNotHandledErr) }
            var hkID = EventHotKeyID()
            GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID),
                              nil, MemoryLayout<EventHotKeyID>.size, nil, &hkID)
            let pressed = GetEventKind(event) == UInt32(kEventHotKeyPressed)
            HotKeys.shared.handlers[hkID.id]?(pressed)
            return noErr
        }, specs.count, &specs, nil, nil)
    }
}

// MARK: - Pasting into the focused app

enum Paster {
    static var canPaste: Bool { AXIsProcessTrusted() }

    static func promptForAccessibility() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }

    /// The user's real clipboard, held while one or more of our pastes are in flight.
    private static var pendingOriginal: [[NSPasteboard.PasteboardType: Data]]?
    private static var restoreWork: DispatchWorkItem?
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Puts text on the clipboard, sends ⌘V, then restores whatever was on the clipboard before.
    /// Returns false when Accessibility isn't granted (text is left on the clipboard instead).
    @discardableResult
    static func paste(_ text: String) -> Bool {
        let pb = NSPasteboard.general
        guard canPaste else { copy(text); return false }

        // Back-to-back pastes keep the first snapshot, so the user's own clipboard is what comes back.
        if pendingOriginal == nil {
            pendingOriginal = (pb.pasteboardItems ?? []).map { item in
                var d: [NSPasteboard.PasteboardType: Data] = [:]
                for t in item.types { if let v = item.data(forType: t) { d[t] = v } }
                return d
            }
        }
        pb.clearContents()
        pb.setString(text, forType: .string)
        // Tell clipboard managers not to record our temporary write.
        pb.setData(Data(), forType: transient)
        pb.setData(Data(), forType: autoGenerated)
        let ourChange = pb.changeCount

        // Private state: physically held hotkey modifiers (⌃⌥) don't leak into the synthetic ⌘V.
        let src = CGEventSource(stateID: .privateState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)

        restoreWork?.cancel()
        let work = DispatchWorkItem {
            defer { pendingOriginal = nil; restoreWork = nil }
            // If something else wrote to the clipboard since, that is newer than our snapshot; keep it.
            guard pb.changeCount == ourChange, let saved = pendingOriginal else { return }
            pb.clearContents()
            if !saved.isEmpty {
                pb.writeObjects(saved.map { dict in
                    let item = NSPasteboardItem()
                    for (t, v) in dict { item.setData(v, forType: t) }
                    return item
                })
            }
        }
        restoreWork = work
        // Generous delay: slow (Electron) apps read the clipboard well after ⌘V arrives.
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.5, execute: work)
        return true
    }

    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }
}

// MARK: - Permissions, sounds, login item

enum Permissions {
    static var micGranted: Bool { AVCaptureDevice.authorizationStatus(for: .audio) == .authorized }

    static func requestMic() async -> Bool {
        if micGranted { return true }
        return await AVCaptureDevice.requestAccess(for: .audio)
    }

    static func openPrivacyPane(_ anchor: String) {
        NSWorkspace.shared.open(URL(string: "x-apple.systempreferences:com.apple.preference.security?\(anchor)")!)
    }
}

enum Sound {
    static func play(_ name: String) {
        guard Prefs.sounds, let s = NSSound(named: NSSound.Name(name)) else { return }
        s.volume = 0.25
        s.play()
    }
}

enum LoginItem {
    static var enabled: Bool { SMAppService.mainApp.status == .enabled }
    static func set(_ on: Bool) {
        do { on ? try SMAppService.mainApp.register() : try SMAppService.mainApp.unregister() }
        catch { NSLog("Murmur: login item \(error)") }
    }
}

// MARK: - Preferences

enum Prefs {
    static let d = UserDefaults.standard
    static func register() {
        d.register(defaults: [
            "cleanup": true,
            "sounds": true,
            "llmModel": "qwen3:4b-instruct",
            "customInstructions": "",
            "vocabulary": "",
            "autoStop": true,
            "speechModel": "ggml-parakeet-tdt-0.6b-v2-q8_0.bin",
            "agentAccount": "",
            "agentCwd": "~/projects",
            "agentFlags": "",
            "autoStopSeconds": 1.2,
        ])
    }
    static var cleanup: Bool { d.bool(forKey: "cleanup") }
    static var sounds: Bool { d.bool(forKey: "sounds") }
    static var llmModel: String { d.string(forKey: "llmModel") ?? "qwen3:4b-instruct" }
    static var customInstructions: String { d.string(forKey: "customInstructions") ?? "" }
    static var autoStop: Bool { d.bool(forKey: "autoStop") }
    static var autoStopSeconds: Double { max(0.5, d.double(forKey: "autoStopSeconds")) }
    static var agentAccount: String { d.string(forKey: "agentAccount") ?? "" }
    static var agentCwd: String { d.string(forKey: "agentCwd") ?? "~/projects" }
    static var agentFlags: String { d.string(forKey: "agentFlags") ?? "" }
    static var speechModel: String { d.string(forKey: "speechModel") ?? "ggml-parakeet-tdt-0.6b-v2-q8_0.bin" }
    static var modelsDir: URL { supportDir.appendingPathComponent("models") }
    /// Parakeet models present on disk (the Silero voice detector is excluded).
    static var availableSpeechModels: [String] {
        ((try? FileManager.default.contentsOfDirectory(atPath: modelsDir.path)) ?? [])
            .filter { $0.hasPrefix("ggml-parakeet") && $0.hasSuffix(".bin") }.sorted()
    }
    static var vocabulary: String { d.string(forKey: "vocabulary") ?? "" }

    static var supportDir: URL {
        let u = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Murmur")
        try? FileManager.default.createDirectory(at: u, withIntermediateDirectories: true)
        return u
    }
    static var vadModelPath: String {
        supportDir.appendingPathComponent("models/ggml-silero-v6.2.0.bin").path
    }
    static var modelPath: String {
        let chosen = modelsDir.appendingPathComponent(speechModel)
        if FileManager.default.fileExists(atPath: chosen.path) { return chosen.path }
        return modelsDir.appendingPathComponent(availableSpeechModels.first ?? speechModel).path
    }
}

// MARK: - History

struct HistoryItem: Codable, Identifiable, Hashable {
    enum Kind: String, Codable { case dictation, ask, agent }
    var id = UUID()
    var date = Date()
    var kind: Kind
    var raw: String
    var text: String
    var app: String?
    var seconds: Double
}

enum HistoryStore {
    static var url: URL { Prefs.supportDir.appendingPathComponent("history.json") }
    static func load() -> [HistoryItem] {
        guard let data = try? Data(contentsOf: url) else { return [] }
        let dec = JSONDecoder(); dec.dateDecodingStrategy = .iso8601
        if let items = try? dec.decode([HistoryItem].self, from: data) { return items }
        // Unreadable (truncated, or an old schema): keep a copy instead of overwriting it on the next save.
        let backup = url.deletingPathExtension().appendingPathExtension("corrupt-\(Int(Date().timeIntervalSince1970)).json")
        try? FileManager.default.moveItem(at: url, to: backup)
        return []
    }
    static func save(_ items: [HistoryItem]) {
        let enc = JSONEncoder(); enc.dateEncodingStrategy = .iso8601
        if let data = try? enc.encode(Array(items.prefix(1000))) { try? data.write(to: url, options: .atomic) }
    }
}
